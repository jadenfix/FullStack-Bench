"""Generate skills/simcloud/reference/*.md from SimCloud's own definitions.

Run after changing kinds, actions, errors, CLI commands or MCP tools:
    uv run python scripts/gen_skill_docs.py
tests/test_skill_docs.py fails if the committed files are stale.
"""

import io
import json
import sys
from contextlib import redirect_stdout
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from simcloud.cli import build_parser  # noqa: E402
from simcloud.errors import CATALOGUE  # noqa: E402
from simcloud.kinds import KINDS, all_actions  # noqa: E402
from simcloud.mcp_server import TOOLS  # noqa: E402

OUT = ROOT / "skills" / "simcloud" / "reference"
HEADER = "<!-- Generated by scripts/gen_skill_docs.py; do not edit by hand. -->\n\n"


def _type(prop: dict, defs: dict) -> str:
    if "$ref" in prop:
        return prop["$ref"].split("/")[-1]
    if "anyOf" in prop:
        return " | ".join(_type(p, defs) for p in prop["anyOf"])
    if "enum" in prop:
        return " | ".join(json.dumps(v) for v in prop["enum"])
    if "const" in prop:
        return json.dumps(prop["const"])
    t = prop.get("type", "any")
    if t == "array":
        return f"list[{_type(prop.get('items', {}), defs)}]"
    if t == "object" and "additionalProperties" in prop and isinstance(prop["additionalProperties"], dict):
        return f"map[string, {_type(prop['additionalProperties'], defs)}]"
    return t


def _fields(schema: dict, defs: dict) -> list[str]:
    rows = ["| field | type | default | description |", "|---|---|---|---|"]
    required = set(schema.get("required", []))
    for name, prop in schema.get("properties", {}).items():
        default = "**required**" if name in required else f"`{json.dumps(prop.get('default'))}`"
        desc = prop.get("description", "").replace("|", "\\|")
        rows.append(f"| `{name}` | {_type(prop, defs).replace('|', '\\|')} | {default} | {desc} |")
    return rows


def kinds_md() -> str:
    out = [HEADER, "# Resource kinds\n",
           "Scope `project` kinds live in environment `_`; scope `env` kinds live in a named environment.\n"]
    for name, info in KINDS.items():
        schema = info.spec.model_json_schema()
        defs = schema.get("$defs", {})
        out += [f"## `{name}` ({info.scope})\n", f"{info.summary}\n",
                f"Verbs: {', '.join(f'`{v}`' for v in info.verbs)}\n", *_fields(schema, defs), ""]
        for dname, d in defs.items():
            out += [f"### `{dname}` (used by `{name}`)\n", *_fields(d, defs), ""]
    return "\n".join(out) + "\n"


def actions_md() -> str:
    lines = [HEADER, "# Actions\n", "Use these in policy statements (`actions`). Patterns like `kv:*` match many.\n"]
    lines += [f"- `{a}`" for a in all_actions()]
    return "\n".join(lines) + "\n"


def errors_md() -> str:
    lines = [HEADER, "# Errors\n", "Every error body is `{\"error\": {\"code\", \"message\", \"details\"}}`.\n",
             "| code | HTTP | meaning |", "|---|---|---|"]
    lines += [f"| `{code}` | {status} | {desc} |" for code, (status, desc) in CATALOGUE.items()]
    return "\n".join(lines) + "\n"


def cli_md() -> str:
    parser = build_parser()
    lines = [HEADER, "# `sc` commands\n", "```", parser.format_help().rstrip(), "```\n"]
    sub = next(a for a in parser._actions if a.__class__.__name__ == "_SubParsersAction")
    for name, p in sub.choices.items():
        lines += [f"## `sc {name}`\n", "```", p.format_help().rstrip(), "```\n"]
    return "\n".join(lines)


def mcp_md() -> str:
    lines = [HEADER, "# MCP tools (`simcloud-mcp`)\n"]
    for name, (desc, schema, _) in TOOLS.items():
        args = ", ".join(f"`{k}`" + ("" if k in schema.get("required", []) else "?") for k in schema["properties"])
        lines.append(f"- **`{name}`**({args}): {desc}")
    return "\n".join(lines) + "\n"


FILES = {"kinds.md": kinds_md, "actions.md": actions_md, "errors.md": errors_md, "cli.md": cli_md,
         "mcp-tools.md": mcp_md}


def render() -> dict[str, str]:
    import os
    os.environ.setdefault("COLUMNS", "100")  # stable argparse wrapping
    return {name: fn() for name, fn in FILES.items()}


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in render().items():
        (OUT / name).write_text(text)
        print(f"wrote {OUT / name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
